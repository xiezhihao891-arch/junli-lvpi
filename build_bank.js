function score(q) {
  const text = (q.q||'') + ' ' + (q.e||'') + ' ' + (q.s||'') + ' ' + (q.o||[]).join(' ');
  let s = 0;
  for (const p of PRI) {
    try { if (new RegExp(p).test(text)) s += 3; } catch(e) {}
  }
  // prefer dates
  if (/\d{4}年/.test(text)) s += 1;
  if (q.t === 'M') s += 0.5;
  if (q.t === 'T') s += 0.3;
  return s;
}

